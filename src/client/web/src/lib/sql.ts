import type { DatabaseContent, Dialect, Field, Relationship, Table } from '../types'
import { quoteIdent } from './dialects'

export interface FkSides {
  childTableId: string
  childFieldId: string
  parentTableId: string
  parentFieldId: string
}

/** The "many" side of a relationship holds the foreign key. */
export function fkSides(rel: Relationship): FkSides {
  if (rel.cardinality === 'one_to_many') {
    return {
      childTableId: rel.endTableId,
      childFieldId: rel.endFieldId,
      parentTableId: rel.startTableId,
      parentFieldId: rel.startFieldId,
    }
  }
  return {
    childTableId: rel.startTableId,
    childFieldId: rel.startFieldId,
    parentTableId: rel.endTableId,
    parentFieldId: rel.endFieldId,
  }
}

const KEYWORD_DEFAULTS = /^(null|true|false|current_timestamp|current_date|current_time|localtimestamp|localtime)$/i

export function formatDefault(value: string): string {
  const v = value.trim()
  if (/^'.*'$/s.test(v)) return v
  if (/^-?\d+(\.\d+)?$/.test(v)) return v
  if (KEYWORD_DEFAULTS.test(v)) return v.toUpperCase()
  if (/^[a-z_][\w.]*\(.*\)$/is.test(v)) return v
  return `'${v.replace(/'/g, "''")}'`
}

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`
const isIntegerType = (t: string) => /int|serial/i.test(t)

function columnDef(f: Field, dialect: Dialect, inlineSqlitePk: boolean): string {
  const q = (n: string) => quoteIdent(n, dialect)
  const parts = [q(f.name), inlineSqlitePk ? 'INTEGER' : f.type.trim() || 'TEXT']

  if (inlineSqlitePk) {
    parts.push('PRIMARY KEY AUTOINCREMENT')
  } else if (f.increment) {
    if (dialect === 'postgresql' && isIntegerType(f.type) && !/serial/i.test(f.type)) {
      parts.push('GENERATED BY DEFAULT AS IDENTITY')
    } else if (dialect === 'mysql' || dialect === 'generic') {
      parts.push('AUTO_INCREMENT')
    } else if (dialect === 'mssql') {
      parts.push('IDENTITY(1,1)')
    }
  }
  if (f.notNull && !f.primary) parts.push('NOT NULL')
  if (f.unique && !f.primary) parts.push('UNIQUE')
  if (f.default.trim() !== '') parts.push('DEFAULT ' + formatDefault(f.default))
  if (dialect === 'mysql' && f.comment.trim()) parts.push('COMMENT ' + sqlString(f.comment))
  return parts.join(' ')
}

function foreignKeyClause(rel: Relationship, tables: Map<string, Table>, dialect: Dialect): { child: Table; clause: string } | null {
  const q = (n: string) => quoteIdent(n, dialect)
  const s = fkSides(rel)
  const child = tables.get(s.childTableId)
  const parent = tables.get(s.parentTableId)
  const childField = child?.fields.find((f) => f.id === s.childFieldId)
  const parentField = parent?.fields.find((f) => f.id === s.parentFieldId)
  if (!child || !parent || !childField || !parentField) return null
  let clause = `FOREIGN KEY (${q(childField.name)}) REFERENCES ${q(parent.name)} (${q(parentField.name)})`
  if (rel.onUpdate !== 'NO ACTION') clause += ` ON UPDATE ${rel.onUpdate}`
  if (rel.onDelete !== 'NO ACTION') clause += ` ON DELETE ${rel.onDelete}`
  return { child, clause }
}

export function fkName(rel: Relationship, tables: Map<string, Table>): string {
  if (rel.name.trim()) return rel.name.trim()
  const s = fkSides(rel)
  const child = tables.get(s.childTableId)
  const parent = tables.get(s.parentTableId)
  const col = child?.fields.find((f) => f.id === s.childFieldId)
  return `fk_${child?.name ?? 'child'}_${col?.name ?? 'col'}_${parent?.name ?? 'parent'}`
}

export function generateSQL(content: DatabaseContent, dialect: Dialect = content.dialect): string {
  const q = (n: string) => quoteIdent(n, dialect)
  const tables = new Map(content.tables.map((t) => [t.id, t]))
  const out: string[] = []
  const trailing: string[] = []

  for (const table of content.tables) {
    const pks = table.fields.filter((f) => f.primary)
    const inlinePk = dialect === 'sqlite' && pks.length === 1 && pks[0].increment ? pks[0] : null
    const lines = table.fields.map((f) => columnDef(f, dialect, f === inlinePk))

    if (pks.length > 0 && !inlinePk) lines.push(`PRIMARY KEY (${pks.map((f) => q(f.name)).join(', ')})`)

    const rels = content.relationships.map((r) => ({ r, fk: foreignKeyClause(r, tables, dialect) }))
    for (const { r, fk } of rels) {
      if (!fk || fk.child.id !== table.id) continue
      if (dialect === 'sqlite') {
        lines.push(`CONSTRAINT ${q(fkName(r, tables))} ${fk.clause}`)
      } else {
        trailing.push(`ALTER TABLE ${q(table.name)} ADD CONSTRAINT ${q(fkName(r, tables))} ${fk.clause};`)
      }
    }

    if (table.comment.trim() && dialect !== 'mysql' && dialect !== 'postgresql') {
      out.push(...table.comment.split('\n').map((l) => `-- ${l}`))
    }
    let stmt = `CREATE TABLE ${q(table.name)} (\n${lines.map((l) => '  ' + l).join(',\n')}\n)`
    if (dialect === 'mysql' && table.comment.trim()) stmt += ` COMMENT=${sqlString(table.comment)}`
    out.push(stmt + ';')

    if (dialect === 'postgresql') {
      if (table.comment.trim()) out.push(`COMMENT ON TABLE ${q(table.name)} IS ${sqlString(table.comment)};`)
      for (const f of table.fields) {
        if (f.comment.trim()) out.push(`COMMENT ON COLUMN ${q(table.name)}.${q(f.name)} IS ${sqlString(f.comment)};`)
      }
    }

    for (const idx of table.indices) {
      const cols = idx.fieldIds
        .map((id) => table.fields.find((f) => f.id === id))
        .filter((f): f is Field => !!f)
        .map((f) => q(f.name))
      if (cols.length === 0) continue
      const name = idx.name.trim() || `idx_${table.name}_${idx.id.slice(0, 6)}`
      out.push(`CREATE ${idx.unique ? 'UNIQUE ' : ''}INDEX ${q(name)} ON ${q(table.name)} (${cols.join(', ')});`)
    }
    out.push('')
  }

  if (trailing.length) out.push(...trailing, '')
  return out.join('\n').trimEnd() + '\n'
}
