import { describe, expect, it } from 'vitest'
import type { DatabaseContent, Field, Table } from '../types'
import { normalizeContent, validate } from './model'
import { formatDefault, generateSQL } from './sql'

const field = (id: string, name: string, type: string, extra: Partial<Field> = {}): Field => ({
  id, name, type, primary: false, notNull: false, unique: false, increment: false, default: '', comment: '', ...extra,
})

const table = (id: string, name: string, fields: Field[]): Table => ({ id, name, x: 0, y: 0, color: '#000', comment: '', fields, indices: [] })

const shop: DatabaseContent = {
  version: 1,
  dialect: 'postgresql',
  tables: [
    table('u', 'users', [field('u1', 'id', 'BIGINT', { primary: true, increment: true }), field('u2', 'email', 'VARCHAR(255)', { notNull: true, unique: true })]),
    table('o', 'orders', [
      field('o1', 'id', 'BIGINT', { primary: true, increment: true }),
      field('o2', 'user_id', 'BIGINT', { notNull: true }),
      field('o3', 'status', 'TEXT', { default: 'draft' }),
    ]),
  ],
  relationships: [
    { id: 'r', name: '', startTableId: 'o', startFieldId: 'o2', endTableId: 'u', endFieldId: 'u1', cardinality: 'many_to_one', onUpdate: 'NO ACTION', onDelete: 'CASCADE' },
  ],
  notes: [],
}

describe('generateSQL', () => {
  it('generates PostgreSQL with identity columns and ALTER TABLE foreign keys', () => {
    const sql = generateSQL(shop, 'postgresql')
    expect(sql).toContain('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY')
    expect(sql).toContain('"email" VARCHAR(255) NOT NULL UNIQUE')
    expect(sql).toContain(`"status" TEXT DEFAULT 'draft'`)
    expect(sql).toContain('PRIMARY KEY ("id")')
    expect(sql).toContain('ALTER TABLE "orders" ADD CONSTRAINT "fk_orders_user_id_users" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE;')
  })

  it('generates MySQL with backticks and AUTO_INCREMENT', () => {
    const sql = generateSQL(shop, 'mysql')
    expect(sql).toContain('`id` BIGINT AUTO_INCREMENT')
    expect(sql).toContain('ALTER TABLE `orders` ADD CONSTRAINT')
  })

  it('inlines foreign keys and autoincrement primary keys for SQLite', () => {
    const sql = generateSQL(shop, 'sqlite')
    expect(sql).toContain('"id" INTEGER PRIMARY KEY AUTOINCREMENT')
    expect(sql).not.toContain('ALTER TABLE')
    expect(sql).toContain('CONSTRAINT "fk_orders_user_id_users" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE')
  })

  it('puts the foreign key on the "many" side for one_to_many', () => {
    const flipped: DatabaseContent = {
      ...shop,
      relationships: [{ ...shop.relationships[0], startTableId: 'u', startFieldId: 'u1', endTableId: 'o', endFieldId: 'o2', cardinality: 'one_to_many' }],
    }
    expect(generateSQL(flipped, 'postgresql')).toContain('ALTER TABLE "orders" ADD CONSTRAINT "fk_orders_user_id_users" FOREIGN KEY ("user_id") REFERENCES "users" ("id")')
  })
})

describe('formatDefault', () => {
  it.each([
    ['0', '0'],
    ['now()', 'now()'],
    ['current_timestamp', 'CURRENT_TIMESTAMP'],
    ["'x'", "'x'"],
    ["it's", "'it''s'"],
  ])('%s -> %s', (input, out) => expect(formatDefault(input)).toBe(out))
})

describe('normalizeContent', () => {
  it('imports drawDB exports', () => {
    const drawdb = {
      database: 'mysql',
      tables: [
        { id: 0, name: 'users', x: 10, y: 20, color: '#175e7a', fields: [{ id: 0, name: 'id', type: 'INT', primary: true, notNull: true, increment: true }] },
        {
          id: 1,
          name: 'posts',
          fields: [
            { id: 0, name: 'id', type: 'INT', primary: true },
            { id: 1, name: 'user_id', type: 'INT' },
            { id: 2, name: 'title', type: 'VARCHAR', size: 120 },
          ],
          indices: [{ id: 0, name: 'idx_title', unique: false, fields: ['title'] }],
        },
      ],
      relationships: [{ id: 0, startTableId: 1, startFieldId: 1, endTableId: 0, endFieldId: 0, cardinality: 'many_to_one', deleteConstraint: 'Cascade', updateConstraint: 'No action' }],
    }
    const c = normalizeContent(drawdb)
    expect(c.dialect).toBe('mysql')
    expect(c.tables[1].fields[2].type).toBe('VARCHAR(120)')
    expect(c.tables[1].indices[0].fieldIds).toEqual(['2'])
    expect(c.relationships[0]).toMatchObject({ startTableId: '1', endTableId: '0', onDelete: 'CASCADE', onUpdate: 'NO ACTION' })
    expect(validate(c).filter((i) => i.level === 'error')).toEqual([])
  })

  it('drops relationships that point at missing columns', () => {
    const c = normalizeContent({ tables: [], relationships: [{ startTableId: 'a', startFieldId: 'b', endTableId: 'c', endFieldId: 'd' }] })
    expect(c.relationships).toEqual([])
  })
})
